#include "libft.h"

void	ft_striteri(char *s, void (*f)(unsigned int, char*))
{
	int	i;
	int	j;

	i = 0;
	j = ft_strlen(s);
	if (s)
	{
		while (i < j)
		{
			f(i, &s[i]);
			i++;
		}
	}
}
